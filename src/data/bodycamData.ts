export type WeaponCategory =
  | 'Assault Rifles'
  | 'SMGs & Machine Pistols'
  | 'Shotguns'
  | 'Sniper Rifles'
  | 'Pistols & Revolvers';

export type FireMode = 'AUTO' | 'SEMI' | 'PUMP' | 'BOLT' | 'BURST';

export interface WeaponVisualSpec {
  receiverColor: number;
  furnitureColor: number;
  metalColor: number;
  barrelLength: number; // meters
  receiverLength: number;
  receiverHeight: number;
  magCurvature: number; // 0 straight, 1 curved AK style
  magLength: number;
  stockStyle: 'tactical' | 'solid' | 'wire' | 'folded' | 'none' | 'sniper' | 'wood';
  handguardStyle: 'quadrail' | 'polymer' | 'wood' | 'compact' | 'shotgun_pump' | 'sniper_fluted' | 'pistol';
  isPistol?: boolean;
  isRevolver?: boolean;
  isBullpup?: boolean;
}

export interface WeaponDef {
  id: string;
  name: string;
  realCounterpart: string;
  category: WeaponCategory;
  slot: 'PRIMARY' | 'SECONDARY';
  caliber: string;
  damage: number; // Bodycam is lethal 1-2 shots (100 HP base)
  headshotMult: number;
  limbMult: number;
  rpm: number;
  fireModes: FireMode[];
  magCapacity: number;
  spareMags: number;
  reloadTimeCalm: number; // seconds
  reloadTimeStressed: number; // seconds (fumble penalty)
  adsSpeed: number; // higher = faster ADS
  switchSpeed: number;
  vRecoil: number; // vertical kick per shot
  hRecoil: number; // horizontal drift per shot
  firstShotKick: number;
  hipSpread: number;
  adsSpread: number;
  pellets?: number; // for shotguns
  muzzleVelocity: number; // m/s
  rpCost: number; // Reissad Points (0 = Free base weapon)
  description: string;
  visual: WeaponVisualSpec;
}

export type AttachmentSlot = 'optic' | 'muzzle' | 'grip' | 'tactical' | 'magazine';

/**
 * In Bodycam v0.8 "Locked & Loaded", Reissad Studio defined 8 exact attachment effects:
 * 1. ADS Speed
 * 2. Switch Speed
 * 3. Reload Speed
 * 4. Horizontal Recoil
 * 5. Vertical Recoil
 * 6. Spread
 * 7. Kick (visual weapon kick)
 * 8. Ammo Capacity
 */
export interface AttachmentModifiers {
  adsSpeed?: number; // multiplier delta e.g. +0.12 or -0.08
  switchSpeed?: number;
  reloadSpeed?: number;
  hRecoil?: number; // negative = reduces recoil
  vRecoil?: number;
  spread?: number;
  kick?: number;
  magCapDelta?: number; // flat bullets added/removed
  suppressed?: boolean;
  opticZoom?: number; // 1.0 = iron, 1.25 = red dot, 1.35 = holo, 2.8 = ACOG, 5.5 = 8x Sniper
  opticType?: 'iron' | 'reddot' | 'holo' | 'acog' | 'sniper8x';
  hasFlashlight?: boolean;
  hasLaser?: boolean;
  laserColor?: number;
}

export interface AttachmentDef {
  id: string;
  name: string;
  slot: AttachmentSlot;
  rpCost: number;
  description: string;
  allowedCategories?: WeaponCategory[];
  modifiers: AttachmentModifiers;
}

